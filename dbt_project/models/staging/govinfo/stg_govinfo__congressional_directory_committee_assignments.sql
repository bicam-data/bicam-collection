/*
   GovInfo CDIR assignment observations.  The seed is generated by
   capture_cdir_committee_assignments.py from official HTML/text renditions.
   It intentionally retains unresolved identities and source text names so
   coverage can be audited without manufacturing a committee edge.
*/
select
    nullif(trim(source_package_id), '') as source_package_id,
    nullif(trim(source_granule_id), '') as source_granule_id,
    nullif(trim(source_url), '') as source_url,
    source_date::date as source_date,
    congress::integer as congress,
    nullif(trim(chamber), '') as chamber,
    nullif(trim(member_name), '') as member_name,
    nullif(trim(member_state), '') as member_state,
    nullif(trim(bioguide_id), '') as bioguide_id,
    nullif(trim(member_match_status), '') as member_match_status,
    nullif(trim(committee_name), '') as committee_name,
    nullif(trim(subcommittee_name), '') as subcommittee_name,
    nullif(trim(committee_code), '') as committee_code,
    nullif(trim(committee_match_status), '') as committee_match_status,
    nullif(trim(role), '') as role,
    nullif(trim(source_text_sha256), '') as source_text_sha256
from {{ ref('govinfo_congressional_directory_committee_assignments') }}
